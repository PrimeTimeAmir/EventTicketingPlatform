-- ============================================
-- V4: Seat holds, bookings and tickets
-- ============================================

-- 1. Seat holds
CREATE TABLE seat_holds (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            hold_reference VARCHAR(64) NOT NULL UNIQUE,

                            event_id BIGINT NOT NULL,

                            user_id BIGINT NOT NULL,

                            expires_at TIMESTAMP WITH TIME ZONE NOT NULL,

                            status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                            created_at TIMESTAMP WITH TIME ZONE
                                NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT fk_seat_holds_event
                                FOREIGN KEY (event_id)
                                    REFERENCES events(id),

                            CONSTRAINT fk_seat_holds_user
                                FOREIGN KEY (user_id)
                                    REFERENCES users(id),

                            CONSTRAINT chk_seat_holds_status
                                CHECK (
                                    status IN (
                                               'ACTIVE',
                                               'CONSUMED',
                                               'EXPIRED',
                                               'RELEASED'
                                        )
                                    )
);

CREATE INDEX idx_seat_holds_event
    ON seat_holds(event_id);

CREATE INDEX idx_seat_holds_user_status
    ON seat_holds(user_id, status);

CREATE INDEX idx_seat_holds_expires_at
    ON seat_holds(expires_at);

-- 2. Seat hold seats: Many-to-Many relation
CREATE TABLE seat_hold_seats (
                                 hold_id BIGINT NOT NULL,

                                 seat_id BIGINT NOT NULL,

                                 CONSTRAINT pk_seat_hold_seats
                                     PRIMARY KEY (hold_id, seat_id),

                                 CONSTRAINT fk_seat_hold_seats_hold
                                     FOREIGN KEY (hold_id)
                                         REFERENCES seat_holds(id)
                                         ON DELETE CASCADE,

                                 CONSTRAINT fk_seat_hold_seats_seat
                                     FOREIGN KEY (seat_id)
                                         REFERENCES seats(id)
);

CREATE INDEX idx_seat_hold_seats_seat
    ON seat_hold_seats(seat_id);

-- 3. Bookings
CREATE TABLE bookings (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          booking_reference VARCHAR(64) NOT NULL UNIQUE,

                          seat_hold_id BIGINT NOT NULL UNIQUE,

                          user_id BIGINT NOT NULL,

                          event_id BIGINT NOT NULL,

                          status VARCHAR(25) NOT NULL DEFAULT 'PENDING',

                          subtotal NUMERIC(12, 2) NOT NULL,

                          fees NUMERIC(12, 2) NOT NULL DEFAULT 0,

                          total NUMERIC(12, 2) NOT NULL,

                          currency VARCHAR(3) NOT NULL DEFAULT 'KZT',

                          created_at TIMESTAMP WITH TIME ZONE
                                                        NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          confirmed_at TIMESTAMP WITH TIME ZONE,

                          cancelled_at TIMESTAMP WITH TIME ZONE,

                          version BIGINT NOT NULL DEFAULT 0,

                          CONSTRAINT fk_bookings_seat_hold
                              FOREIGN KEY (seat_hold_id)
                                  REFERENCES seat_holds(id),

                          CONSTRAINT fk_bookings_user
                              FOREIGN KEY (user_id)
                                  REFERENCES users(id),

                          CONSTRAINT fk_bookings_event
                              FOREIGN KEY (event_id)
                                  REFERENCES events(id),

                          CONSTRAINT chk_bookings_status
                              CHECK (
                                  status IN (
                                             'PENDING',
                                             'CONFIRMED',
                                             'CANCELLED',
                                             'PAYMENT_FAILED'
                                      )
                                  ),

                          CONSTRAINT chk_bookings_amounts
                              CHECK (
                                  subtotal >= 0
                                      AND fees >= 0
                                      AND total >= 0
                                  ),

                          CONSTRAINT chk_bookings_total
                              CHECK (total = subtotal + fees),

                          CONSTRAINT chk_bookings_currency
                              CHECK (currency ~ '^[A-Z]{3}$')
    );

CREATE INDEX idx_bookings_user
    ON bookings(user_id);

CREATE INDEX idx_bookings_event
    ON bookings(event_id);

CREATE INDEX idx_bookings_status
    ON bookings(status);

-- 4. Tickets
CREATE TABLE tickets (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                         ticket_code VARCHAR(64) NOT NULL UNIQUE,

                         booking_id BIGINT NOT NULL,

                         event_id BIGINT NOT NULL,

                         seat_id BIGINT NOT NULL,

                         status VARCHAR(20) NOT NULL DEFAULT 'ISSUED',

                         issued_at TIMESTAMP WITH TIME ZONE
                                                 NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         checked_in_at TIMESTAMP WITH TIME ZONE,

                         price_paid NUMERIC(12, 2) NOT NULL,

                         CONSTRAINT fk_tickets_booking
                             FOREIGN KEY (booking_id)
                                 REFERENCES bookings(id),

                         CONSTRAINT fk_tickets_event
                             FOREIGN KEY (event_id)
                                 REFERENCES events(id),

                         CONSTRAINT fk_tickets_seat
                             FOREIGN KEY (seat_id)
                                 REFERENCES seats(id),

                         CONSTRAINT chk_tickets_status
                             CHECK (
                                 status IN (
                                            'ISSUED',
                                            'CHECKED_IN',
                                            'CANCELLED',
                                            'REFUNDED'
                                     )
                                 ),

                         CONSTRAINT chk_tickets_price
                             CHECK (price_paid >= 0),

                         CONSTRAINT uq_ticket_event_seat
                             UNIQUE (event_id, seat_id)
);

CREATE INDEX idx_tickets_booking
    ON tickets(booking_id);

CREATE INDEX idx_tickets_seat
    ON tickets(seat_id);
