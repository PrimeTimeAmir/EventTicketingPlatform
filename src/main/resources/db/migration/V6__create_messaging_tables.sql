-- ============================================
-- V6: Messaging and Audit
-- ============================================

-- 1. Outbox messages
CREATE TABLE outbox_messages (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 aggregate_type VARCHAR(100) NOT NULL,

                                 aggregate_id VARCHAR(100) NOT NULL,

                                 event_type VARCHAR(100) NOT NULL,

                                 payload JSONB NOT NULL,

                                 created_at TIMESTAMP WITH TIME ZONE
                                                             NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 published_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_outbox_unpublished
    ON outbox_messages(created_at)
    WHERE published_at IS NULL;

-- 2. Processed messages
CREATE TABLE processed_messages (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                    message_id VARCHAR(100) NOT NULL UNIQUE,

                                    consumed_at TIMESTAMP WITH TIME ZONE
                                                            NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Audit entries
CREATE TABLE audit_entries (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               actor_id BIGINT,

                               action VARCHAR(100) NOT NULL,

                               entity_type VARCHAR(100) NOT NULL,

                               entity_id VARCHAR(100) NOT NULL,

                               created_at TIMESTAMP WITH TIME ZONE
                                   NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_audit_entries_actor
                                   FOREIGN KEY (actor_id)
                                       REFERENCES users(id)
                                       ON DELETE SET NULL
);

CREATE INDEX idx_audit_entries_actor
    ON audit_entries(actor_id);

CREATE INDEX idx_audit_entries_entity
    ON audit_entries(entity_type, entity_id);

CREATE INDEX idx_audit_entries_created_at
    ON audit_entries(created_at);
