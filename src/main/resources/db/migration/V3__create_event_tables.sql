-- ============================================
-- V3: Events and event section prices
-- ============================================

-- 1. Events
CREATE TABLE events (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                        venue_id BIGINT NOT NULL,

                        organizer_id BIGINT NOT NULL,

                        title VARCHAR(200) NOT NULL,

                        description TEXT,

                        starts_at TIMESTAMP WITH TIME ZONE NOT NULL,

                        doors_open_at TIMESTAMP WITH TIME ZONE NOT NULL,

                        sales_open_at TIMESTAMP WITH TIME ZONE NOT NULL,

                        sales_close_at TIMESTAMP WITH TIME ZONE NOT NULL,

                        status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

                        created_at TIMESTAMP WITH TIME ZONE
                            NOT NULL DEFAULT CURRENT_TIMESTAMP,

                        CONSTRAINT fk_events_venue
                            FOREIGN KEY (venue_id)
                                REFERENCES venues(id),

                        CONSTRAINT fk_events_organizer
                            FOREIGN KEY (organizer_id)
                                REFERENCES users(id),

                        CONSTRAINT chk_events_status
                            CHECK (
                                status IN (
                                           'DRAFT',
                                           'PUBLISHED',
                                           'CANCELLED',
                                           'COMPLETED'
                                    )
                                ),

                        CONSTRAINT chk_events_sales_period
                            CHECK (sales_open_at < sales_close_at),

                        CONSTRAINT chk_events_doors
                            CHECK (doors_open_at <= starts_at)
);

CREATE INDEX idx_events_venue
    ON events(venue_id);

CREATE INDEX idx_events_organizer
    ON events(organizer_id);

CREATE INDEX idx_events_status_starts
    ON events(status, starts_at);

-- 2. Event section prices
CREATE TABLE event_section_prices (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                      event_id BIGINT NOT NULL,

                                      section_id BIGINT NOT NULL,

                                      price NUMERIC(12, 2) NOT NULL,

                                      currency VARCHAR(3) NOT NULL DEFAULT 'KZT',

                                      CONSTRAINT fk_event_section_prices_event
                                          FOREIGN KEY (event_id)
                                              REFERENCES events(id)
                                              ON DELETE CASCADE,

                                      CONSTRAINT fk_event_section_prices_section
                                          FOREIGN KEY (section_id)
                                              REFERENCES sections(id),

                                      CONSTRAINT chk_event_section_prices_price
                                          CHECK (price >= 0),

                                      CONSTRAINT uq_event_section_price
                                          UNIQUE (event_id, section_id)
);

CREATE INDEX idx_event_section_prices_section
    ON event_section_prices(section_id);
