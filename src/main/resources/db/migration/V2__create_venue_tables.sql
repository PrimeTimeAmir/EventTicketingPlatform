-- ============================================
-- V2: Venue, Section and Seat tables
-- ============================================

-- 1. Venues
CREATE TABLE venues (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                        name VARCHAR(150) NOT NULL,

                        address_line VARCHAR(255) NOT NULL,

                        city VARCHAR(100) NOT NULL,

                        timezone VARCHAR(64) NOT NULL,

                        total_capacity INTEGER NOT NULL,

                        CONSTRAINT chk_venues_capacity
                            CHECK (total_capacity > 0)
);

-- 2. Sections
CREATE TABLE sections (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          venue_id BIGINT NOT NULL,

                          name VARCHAR(100) NOT NULL,

                          row_count INTEGER NOT NULL,

                          seats_per_row INTEGER NOT NULL,

                          price_tier VARCHAR(50) NOT NULL,

                          CONSTRAINT fk_sections_venue
                              FOREIGN KEY (venue_id)
                                  REFERENCES venues(id)
                                  ON DELETE CASCADE,

                          CONSTRAINT chk_sections_row_count
                              CHECK (row_count > 0),

                          CONSTRAINT chk_sections_seats_per_row
                              CHECK (seats_per_row > 0),

                          CONSTRAINT uq_sections_venue_name
                              UNIQUE (venue_id, name)
);

CREATE INDEX idx_sections_venue
    ON sections(venue_id);

-- 3. Seats
CREATE TABLE seats (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       section_id BIGINT NOT NULL,

                       row_label VARCHAR(10) NOT NULL,

                       seat_number INTEGER NOT NULL,

                       accessible BOOLEAN NOT NULL DEFAULT FALSE,

                       CONSTRAINT fk_seats_section
                           FOREIGN KEY (section_id)
                               REFERENCES sections(id)
                               ON DELETE CASCADE,

                       CONSTRAINT chk_seats_number
                           CHECK (seat_number > 0),

                       CONSTRAINT uq_seat_position
                           UNIQUE (section_id, row_label, seat_number)
);

CREATE INDEX idx_seats_section
    ON seats(section_id);
